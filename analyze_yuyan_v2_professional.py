import json
import re
from typing import Dict, List, Tuple
from collections import defaultdict


class YuyanAnalyzerV2:
    """言语理解专业分析器V2.0 - 基于考点分布体系"""

    def __init__(self):
        """初始化分析器"""
        self.data = []
        self.analysis_results = {
            '题型频次': defaultdict(int),
            '一级分类': defaultdict(int),
            '二级分类': defaultdict(int),
            '三级分类': defaultdict(int),
            '年份分布': defaultdict(lambda: defaultdict(int)),
            '关键词统计': defaultdict(int),
            '陷阱类型': defaultdict(int)
        }

        # 江苏省考言语理解特色
        self.jiangsu_features = {
            '逻辑填空': [
                '高频考查词义侧重辨析(拆词法)',
                '限定信息四大类型(解释说明/搭配对象/感情色彩/逻辑关系)',
                '成语辨析侧重典故与含义',
                '多空题注重逻辑关联词的运用'
            ],
            '片段阅读': [
                '主旨概括:五个不重要(背景/举例/原因/援引/反面)',
                '主旨概括:五个关系(递进/并列/转折/因果/总分)',
                '主体话题法:找主题词是关键',
                '行文脉络:总分/分总/并列/递进/转折'
            ],
            '语句表达': [
                '语句排序:首句特征+关联词+指代词+逻辑顺序',
                '语句衔接:话题一致+思路连贯',
                '下文推断:尾句话题延续'
            ]
        }

    def load_data(self, file_path: str):
        """加载JSON数据"""
        with open(file_path, 'r', encoding='utf-8') as f:
            self.data = json.load(f)
        print(f"✅ 已加载 {len(self.data)} 道题目")

    def identify_detailed_question_type(self, item: Dict) -> Tuple[str, str, str]:
        """
        精细化题型识别 - 基于考点分布.md的三级分类体系
        返回: (一级分类, 二级分类, 三级分类)

        一级分类(4类):
        - 逻辑填空
        - 片段阅读
        - 篇章阅读
        - 语句表达

        二级分类(11类):
        逻辑填空: 近义词辨析、成语辨析、混合辨析
        片段阅读: 主旨概括、意图判断、细节查找、语句理解、代词指代
        语句表达: 语句衔接、语句排序、下文推断
        篇章阅读: 细节查找、语句衔接、标题选择

        三级分类(30+类): 更细化的具体题型
        """
        题干 = item.get('题干', '')
        解析 = item.get('解析', '')
        原题型 = item.get('题型识别', '')

        # 一级分类判断
        一级 = self._identify_level1(题干, 解析, 原题型)

        # 二级分类判断
        二级 = self._identify_level2(一级, 题干, 解析, 原题型)

        # 三级分类判断
        三级 = self._identify_level3(一级, 二级, 题干, 解析, 原题型, item)

        return 一级, 二级, 三级

    def _identify_level1(self, 题干: str, 解析: str, 原题型: str) -> str:
        """识别一级分类"""
        # 逻辑填空特征
        if '填入' in 题干 or '划横线' in 题干 or '空缺' in 题干:
            return '逻辑填空'
        if '逻辑填空' in 原题型:
            return '逻辑填空'

        # 语句表达特征
        if '语句排序' in 原题型 or '排序' in 题干:
            return '语句表达'
        if '下文推断' in 原题型 or '接下来' in 题干 or '下文' in 题干:
            return '语句表达'
        if '语句衔接' in 原题型 or '衔接' in 题干:
            return '语句表达'
        if '标题' in 题干 or '标题' in 原题型:
            return '语句表达'

        # 篇章阅读特征(多段材料)
        if '材料' in 原题型 or '篇章' in 原题型:
            return '篇章阅读'

        # 片段阅读(默认)
        return '片段阅读'

    def _identify_level2(self, 一级: str, 题干: str, 解析: str, 原题型: str) -> str:
        """识别二级分类"""
        if 一级 == '逻辑填空':
            # 检查是否为成语题
            if '成语' in 解析 or ('A、' in 题干 and len(题干.split('A、')[1].split('B、')[0].strip()) <= 8):
                return '成语辨析'
            # 默认为近义词辨析
            return '近义词辨析'

        elif 一级 == '片段阅读':
            if '主旨' in 题干 or '主旨' in 解析 or '主要' in 题干:
                return '主旨概括'
            if '意图' in 题干 or '想要说明' in 题干 or '目的' in 题干:
                return '意图判断'
            if '细节' in 解析 or '符合' in 题干 or '正确' in 题干:
                return '细节判断'
            if '理解' in 题干 or '含义' in 题干 or '指的是' in 题干:
                return '语句理解'
            if '代词' in 解析 or '指代' in 题干:
                return '代词指代'
            # 默认主旨概括
            return '主旨概括'

        elif 一级 == '语句表达':
            if '排序' in 题干 or '排序' in 原题型:
                return '语句排序'
            if '下文' in 题干 or '接下来' in 题干:
                return '下文推断'
            if '标题' in 题干:
                return '标题填入'
            return '语句衔接'

        elif 一级 == '篇章阅读':
            if '标题' in 题干:
                return '标题选择'
            if '衔接' in 题干:
                return '语句衔接'
            return '细节查找'

        return '其他'

    def _identify_level3(self, 一级: str, 二级: str, 题干: str, 解析: str, 原题型: str, item: Dict) -> str:
        """识别三级分类"""

        if 一级 == '逻辑填空' and 二级 == '近义词辨析':
            # 分析填空数量
            选项 = item.get('选项', {})
            if 选项:
                空数 = 题干.count('＿') + 题干.count('_')
                if 空数 >= 4:
                    return '四空及以上'
                elif 空数 == 3:
                    return '三空'
                elif 空数 == 2:
                    return '两空'
                else:
                    return '单空'

            # 根据解析判断具体类型
            if '词义侧重' in 解析 or '侧重' in 解析:
                return '词义侧重'
            if '搭配' in 解析:
                return '搭配对象'
            if '感情色彩' in 解析 or '褒义' in 解析 or '贬义' in 解析:
                return '感情色彩'
            if '因果' in 解析 or '转折' in 解析 or '递进' in 解析:
                return '逻辑关联词'
            return '单空'

        elif 一级 == '逻辑填空' and 二级 == '成语辨析':
            空数 = 题干.count('＿') + 题干.count('_')
            if 空数 >= 2:
                return '两空及以上'
            return '单空'

        elif 一级 == '片段阅读' and 二级 == '主旨概括':
            # 根据行文脉络判断
            if '转折' in 解析 or '但是' in 题干 or '然而' in 题干:
                return '转折文段'
            if '因此' in 题干 or '所以' in 题干 or '因果' in 解析:
                return '因果文段'
            if '递进' in 解析 or '更' in 题干 or '甚至' in 题干:
                return '递进文段'
            if '总分' in 解析:
                return '总分文段'
            if '分总' in 解析:
                return '分总文段'
            if '并列' in 解析:
                return '并列文段'
            return '综合文段'

        elif 一级 == '片段阅读' and 二级 == '细节判断':
            if '符合' in 题干:
                return '细节查找-符合项'
            if '不符' in 题干 or '错误' in 题干:
                return '细节查找-不符项'
            return '细节查找'

        elif 一级 == '语句表达' and 二级 == '语句排序':
            return '六句排序' if '⑥' in 题干 else '五句排序'

        return 二级

    def generate_detailed_content(self, item: Dict, 一级: str, 二级: str, 三级: str) -> str:
        """
        生成专业的考察内容描述(300字)
        基于考点分布.md的专业知识体系
        """
        题干 = item.get('题干', '')
        解析 = item.get('解析', '')

        # 逻辑填空的考察内容
        if 一级 == '逻辑填空':
            if 二级 == '近义词辨析':
                if '词义侧重' in 三级 or '单空' in 三级:
                    return f"""本题考查近义词辨析能力,核心是词义侧重的精准把握。考察内容包括:①拆词法-将词语拆分理解侧重点;②语境对应法-根据上下文语境选择侧重点匹配的词;③搭配对象法-根据搭配习惯判断。
核心能力:词汇积累+语境分析+语感培养。
江苏特色:高频考查实词辨析,侧重词义的细微差别,需要考生具备扎实的词汇功底和语境敏感度。常见陷阱:①词义相近但侧重点不同;②忽略语境的提示信息;③被干扰项的表面意思迷惑。
解题关键:找准语境中的关键提示词,运用拆词法分析侧重点,选择与语境最契合的选项。"""

                elif '搭配对象' in 三级:
                    return f"""本题考查词语搭配能力,核心是固定搭配和习惯用法的掌握。考察内容包括:①主谓搭配-主语与谓语的合理性;②动宾搭配-动词与宾语的常用组合;③定中搭配-定语与中心语的修饰关系;④状中搭配-状语与中心语的限制关系。
核心能力:语言规范性+搭配习惯+语感积累。
江苏特色:侧重考查书面语的规范搭配,尤其是公文用语、学术用语的固定搭配。常见陷阱:①搭配不当但语义相近;②口语化表达与书面语混淆;③忽略词语的适用范围。
解题关键:积累常见固定搭配,注意词语的使用场合,优先选择规范的书面表达。"""

                elif '逻辑关联词' in 三级:
                    return f"""本题考查逻辑关联词的运用,核心是上下文逻辑关系的判断。考察内容包括:①并列关系(而且/同时/也);②递进关系(甚至/更/进而);③转折关系(但是/却/然而);④因果关系(因此/所以/导致);⑤假设关系(如果/假使);⑥条件关系(只要/只有)。
核心能力:逻辑思维+关系判断+语境理解。
江苏特色:多空题常考逻辑关联词,需要整体把握句间关系,注重上下文的连贯性。常见陷阱:①关系判断错误;②忽略递进与并列的区别;③转折关系的前后逻辑混淆。
解题关键:先判断句间逻辑关系,再选择对应的关联词,注意关联词的固定搭配(不但...而且、虽然...但是等)。"""

            elif 二级 == '成语辨析':
                return f"""本题考查成语辨析能力,核心是成语含义、用法、适用对象的准确理解。考察内容包括:①成语本义-典故来源与基本含义;②成语引申义-现代语境中的常用意义;③成语感情色彩-褒义/贬义/中性;④成语适用对象-人/物/事的限制;⑤成语语法功能-作谓语/定语/状语等。
核心能力:成语积累+典故理解+语境判断。
江苏特色:侧重考查书面语中的常用成语,注重成语的准确性和规范性,避免望文生义。常见陷阱:①望文生义-仅从字面理解;②张冠李戴-用错适用对象;③感情色彩错误-褒贬混用;④语法功能不当。
解题关键:准确理解成语本义,注意适用对象和感情色彩,避免想当然的理解。"""

        # 片段阅读的考察内容
        elif 一级 == '片段阅读':
            if 二级 == '主旨概括':
                if '转折文段' in 三级:
                    return f"""本题考查转折文段的主旨概括能力,核心是转折后内容的快速定位。考察内容包括:①转折词识别(但是/却/然而/不过);②转折前后逻辑-前铺垫后重点;③主旨句定位-转折后是重点;④主题词提取-找准核心话题。
核心能力:关联词敏感度+主旨提炼+快速定位。
江苏特色:转折文段高频考查,＂但是＂后是重点,需快速锁定转折词。五个不重要:背景铺垫/举例论证/原因解释/援引观点/反面论证,这些都不是主旨。常见陷阱:①被转折前内容迷惑;②选择片面项;③过度引申。
解题关键:优先看转折词,转折后是重点,结合主题词快速锁定主旨句,排除片面项和无关项。"""

                elif '因果文段' in 三级:
                    return f"""本题考查因果文段的主旨概括能力,核心是结论句的快速识别。考察内容包括:①结论词识别(因此/所以/可见/总之);②因果逻辑-前因后果;③主旨句定位-结论句是重点;④主题词验证-结论句需包含主题词。
核心能力:逻辑推理+结论定位+主题把握。
江苏特色:因果文段注重结论句,＂因此＂＂所以＂后是重点。需要注意的是,有些文段会出现假结论(前文的小结论),真正的主旨在最后的总结论。常见陷阱:①被原因部分迷惑;②选择过程而非结论;③忽略最后的总结论。
解题关键:优先看结论词,结论句是重点,验证是否包含主题词,排除原因部分和过程描述。"""

                elif '递进文段' in 三级:
                    return f"""本题考查递进文段的主旨概括能力,核心是递进后内容的把握。考察内容包括:①递进词识别(更/甚至/尤其/进而);②递进逻辑-前浅后深;③主旨句定位-递进后是重点;④程度把握-递进后程度更深。
核心能力:程度感知+逻辑递进+重点定位。
江苏特色:递进文段侧重＂更＂＂甚至＂后的内容,体现由浅入深、由轻到重的逻辑。五个关系中递进关系需要特别注意程度的变化。常见陷阱:①选择递进前内容;②程度把握不准;③忽略＂尤其＂＂特别是＂等关键词。
解题关键:找准递进词,递进后是重点,注意程度的加深,选择最深层次的内容作为主旨。"""

                else:  # 综合文段、并列文段等
                    return f"""本题考查主旨概括能力,核心是主旨句的快速定位和主题词的准确提取。考察内容包括:①主题词识别-高频词/核心概念;②行文脉络分析-总分/分总/并列/递进/转折;③主旨句定位-关联词法/主体话题法;④选项对比-排除片面/无关/过度引申。
核心能力:主题把握+结构分析+快速定位。
江苏特色:主旨概括是言语理解的核心题型,占比最高。需掌握五个不重要(背景铺垫/举例论证/原因解释/援引观点/反面论证)和五个关系(递进/并列/转折/因果/总分)。主体话题法:找准文段的主题词是关键,主旨句必须包含主题词。常见陷阱:①片面项-只说一部分;②无关项-未提及核心话题;③过度引申-推断过度。
解题关键:①找主题词(高频词、核心概念);②找关联词(转折优先、结论次之);③排除片面项、无关项、过度引申项,选择全面准确的同义替换。"""

            elif 二级 == '细节判断':
                return f"""本题考查细节判断能力,核心是选项与原文的精准比对。考察内容包括:①时间陷阱-时间范围的混淆;②数量陷阱-数据的偷换;③概念陷阱-概念的混淆;④范围陷阱-范围的扩大缩小;⑤逻辑陷阱-因果/充要条件的混淆;⑥程度陷阱-绝对化表述(一定/必然/全部)。
核心能力:细节敏感度+比对能力+陷阱识别。
江苏特色:细节判断侧重陷阱识别而非复杂推理,需要逐字比对原文与选项。常见的六大陷阱需要重点关注:时间/数量/概念/范围/逻辑/程度。采用排除法,先易后难,遇到难以判断的选项可暂时跳过。
解题关键:回文定位,逐字比对,识别常见陷阱,注意绝对化表述(往往错误)和可能性表述(往往正确),优先排除明显错误项。"""

            elif 二级 == '语句理解':
                return f"""本题考查语句理解能力,核心是结合语境理解特定句子的深层含义。考察内容包括:①代词指代-指代对象的确定;②句子含义-结合语境理解言外之意;③修辞理解-比喻/拟人等修辞手法;④关键词理解-特定词语在语境中的含义。
核心能力:语境理解+深层阅读+言外之意把握。
江苏特色:语句理解注重结合上下文,不能脱离语境孤立理解。需要关注前后文的逻辑关系和作者的表达意图。
解题关键:①定位划线句子;②分析上下文语境;③理解作者意图;④选择最贴合语境的同义替换,避免字面理解和过度引申。"""

        # 语句表达的考察内容
